/* platform/esp32_idf/main/main.c
 *
 * Stage 14 14a -- three app_main paths selected at compile time.
 *
 *   STANDALONE        (default; same as 13b):
 *     Real DS18B20 + tach + LEDC fan.  Sensor at 1 Hz, core at
 *     10 Hz, status line at 1 Hz.  Drives the bench rig.
 *
 *   REPLAY_STANDALONE (-DTHERMALCORE_REPLAY_STANDALONE=ON):
 *     No BSP init.  Walks `G_REPLAY_TICKS[]` (see
 *     replay_fixture.c), feeds each row through
 *     thermal_core_step(), lets the callbacks emit canonical
 *     CSV rows, prints `END\n`, parks.  Stage 15 uses this
 *     output for host-vs-target byte-for-byte parity.
 *
 *   HIL_PERIPHERAL    (-DTHERMALCORE_HIL_PERIPHERAL=ON):
 *     Real BSPs, no thermal_core_step() (the Linux daemon
 *     owns the control loop).  Loop reads sensor (1 Hz
 *     cached) + tach delta (10 Hz), encodes each as a
 *     TELEM_SAMPLE TC frame, writes to USB-Serial-JTAG.
 *     PWM parked at 0 duty until 14b wires the inbound
 *     CMD_REQUEST path.
 *
 * The portable `core/` source is linked unchanged in
 * STANDALONE and REPLAY.  HIL skips it (the daemon runs
 * thermal_core_step instead) but `protocol/thermal_wire.c`
 * comes in via thermal_wire_encode_telem_sample.
 * G_THERMAL_CFG is generated by tools/json2static.py from
 * configs/esp32-c3-standalone.json.
 *
 * Pin map (STANDALONE + HIL):
 *   GPIO 4 -- fan PWM out (25 kHz, 3.3 V)
 *   GPIO 5 -- fan tach in (10k pull-up to 3.3 V)
 *   GPIO 6 -- DS18B20 1-Wire data (4.7k pull-up to 3.3 V)
 *
 * See PRD section 4.2 + 8.3 and impl-plan section 5
 * Stages 13 + 14.
 */
