void app_main(void)
{
#if defined(THERMALCORE_MODE_HIL_PERIPHERAL)
    app_main_hil_peripheral();
#elif defined(THERMALCORE_MODE_REPLAY_STANDALONE)
    app_main_replay();
#else
    app_main_standalone();
#endif
}
